function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="fr">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const isBareLayout = pathname === "/" || pathname.startsWith("/supervisor");

  useEffect(() => {
    enforceHttps();
    registerServiceWorker();
  }, []);

  return (
    <QueryClientProvider client={queryClient}>
      <I18nProvider>
        <AuthProvider>
          <OfflineIndicator />
          <AuthGate>
            {isBareLayout ? (
              <Outlet />
            ) : (
              <AppShell>
                <Outlet />
              </AppShell>
            )}
          </AuthGate>
        </AuthProvider>
      </I18nProvider>
    </QueryClientProvider>
  );
}
